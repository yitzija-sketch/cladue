#!/usr/bin/env python3
"""Compute the final-summary tables from the consolidated CSVs and write parts/_runs/SUMMARY_TABLES.md
(counts per file, verification coverage, top-20 buyers, buyer types by information depth, coverage by
year/county, undated share). The narrative (top-10 questions etc.) is written by hand into FINAL_SUMMARY.md.

Run: python3 -I buyers_research/tools/make_summary.py
"""
import csv
import glob
import json
import os
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rd(name):
    with open(os.path.join(ROOT, name), encoding='utf-8') as f:
        return list(csv.DictReader(f))


A = rd('buyers_stated.csv')
B = rd('deals_public_2019_2024.csv')
C = rd('buyer_entities.csv')
D = rd('market_buyer_mix.csv')
R = rd('buyer_activity_rank.csv')
rej = rd('rejected_rows.csv')
rep = json.load(open(os.path.join(ROOT, 'consolidate_report.json')))
dossiers = sorted(glob.glob(os.path.join(ROOT, 'dossier_*.md')))


def tagcount(rows, col='verification'):
    c = Counter()
    n = 0
    for r in rows:
        if r.get(col):
            n += 1
            for t in r[col].split(';'):
                if t:
                    c[t.split(':')[0]] += 1
    return n, dict(c)


L = []
L.append('# Summary tables (generated by tools/make_summary.py)\n')
L.append('## Counts per file\n')
L.append('| File | Rows | Notes |')
L.append('|---|---|---|')
a_crit = sum(1 for r in A if any(r[f] for f in ('min_sf', 'max_sf', 'min_price', 'max_price', 'stated_criteria_quote')))
a_head = sum(1 for r in A if r['acquisitions_head_name'])
a_nj = Counter(r['nj_active'].lower() for r in A)
vA = tagcount(A)
L.append(f"| buyers_stated.csv | {len(A)} buyers | {a_crit} with stated criteria, {a_head} with a named acquisitions head; NJ-active yes {a_nj.get('yes',0)} / unknown {a_nj.get('unknown',0)} / no {a_nj.get('no',0)}; {vA[0]} rows carry verification tags {vA[1]} |")
b_dated = sum(1 for r in B if r['date'])
b_port = sum(1 for r in B if r['address'].upper().startswith('PORTFOLIO'))
b_price = sum(1 for r in B if r['price'])
b_sf = sum(1 for r in B if r['sf'])
b_small = sum(1 for r in B if r['sf'] and float(r['sf']) < 250000)
b_spv = sum(1 for r in B if r['buyer_spv_named'])
vB = tagcount(B)
by_year = Counter((r['date'][:4] if r['date'] else 'undated') for r in B)
L.append(f"| deals_public_2019_2024.csv | {len(B)} properties ({b_port} portfolio summary rows) | dated {b_dated} / undated {len(B)-b_dated}; {b_price} with price, {b_sf} with SF ({b_small} under 250K SF), {b_spv} with buying LLC named; {vB[0]} rows carry verification tags {vB[1]} |")
c_buyers = len(set(r['name_key'] for r in C))
c_roles = Counter(r['entity_role'] for r in C)
c_ev = Counter(r['evidence_type'] for r in C)
vC = tagcount(C)
L.append(f"| buyer_entities.csv | {len(C)} entities for {c_buyers} buyers | roles {dict(c_roles)}; evidence {dict(c_ev.most_common(8))}; {vC[0]} rows carry verification tags {vC[1]} |")
d_metrics = Counter(r['metric'] for r in D)
d_years = Counter(r['year'] for r in D)
L.append(f"| market_buyer_mix.csv | {len(D)} metric rows | years {dict(sorted(d_years.items()))}; top metrics {dict(d_metrics.most_common(10))} |")
L.append(f"| buyer_activity_rank.csv | {len(R)} | activity score = 2 x press deals 2019-24 + NJ deals seen in A + 1 if in A |")
L.append(f"| dossier_*.md | {len(dossiers)} | one page per buyer |")
L.append(f"| rejected_rows.csv | {len(rej)} | {dict(Counter(r['reason'].split(' (')[0] for r in rej))} |")
L.append('')
L.append('## Deals by year\n')
L.append('| ' + ' | '.join(sorted(by_year)) + ' |')
L.append('|' + '---|' * len(by_year))
L.append('| ' + ' | '.join(str(by_year[k]) for k in sorted(by_year)) + ' |')
L.append('')
by_county = Counter(r['county'] or 'blank' for r in B)
L.append('## Deals by county\n')
L.append(', '.join(f'{k} {v}' for k, v in by_county.most_common()))
L.append('')
L.append('## Buyer types in buyers_stated.csv (and how much the public web says about each)\n')
L.append('| buyer_type | buyers | with stated criteria | with acquisitions head | NJ-active yes |')
L.append('|---|---|---|---|---|')
bt = defaultdict(list)
for r in A:
    bt[r['buyer_type']].append(r)
for k, rs in sorted(bt.items(), key=lambda kv: -len(kv[1])):
    L.append(f"| {k} | {len(rs)} | {sum(1 for r in rs if any(r[f] for f in ('min_sf','max_sf','min_price','max_price','stated_criteria_quote')))} | {sum(1 for r in rs if r['acquisitions_head_name'])} | {sum(1 for r in rs if r['nj_active'].lower()=='yes')} |")
L.append('')
L.append('## 25 most active buyers (press deals 2019-2024 + NJ deals seen while researching; call-list buyers excluded)\n')
L.append('| # | Buyer | Type | Press deal rows | NJ deals seen (A) | Entities found | Stated buy box? |')
L.append('|---|---|---|---|---|---|---|')
Amap = {r['name_key']: r for r in A}
CALL = {'CENTERPOINT PROPERTIES', 'TERRENO REALTY', 'CABOT PROPERTIES', 'SITEX GROUP', 'ELBERON DEVELOPMENT GROUP', 'KURV INDUSTRIAL', 'BRIDGE INDUSTRIAL'}
i = 0
for r in R:
    k = r['name_key']
    if not r['buyer_name'] or k in CALL or any(u in k for u in ('UNNAMED', 'PRIVATE')):
        continue
    a = Amap.get(k, {})
    if a.get('nj_active', '').lower() == 'no':
        continue
    i += 1
    bb = 'yes' if any(a.get(f) for f in ('min_sf', 'max_sf', 'min_price', 'max_price', 'stated_criteria_quote')) else 'no'
    L.append(f"| {i} | {r['buyer_name']} | {r['buyer_type']} | {r['press_deal_rows_2019_2024']} | {r['nj_deal_count_seen_A']} | {r['entities_found']} | {bb} |")
    if i >= 25:
        break
L.append('')
L.append('## Call-list buyers (deliberately low effort; shown for completeness)\n')
for r in R:
    if r['name_key'] in CALL:
        L.append(f"- {r['buyer_name'] or r['name_key']}: {r['press_deal_rows_2019_2024']} press deal rows, {r['entities_found']} entities")
L.append('')
out = os.path.join(ROOT, 'parts', '_runs', 'SUMMARY_TABLES.md')
with open(out, 'w', encoding='utf-8') as f:
    f.write('\n'.join(L) + '\n')
print('\n'.join(L))
